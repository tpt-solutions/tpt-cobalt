/// A block of Pythonic statements that expands to plain `tpt_*` calls.
///
/// Supported statement forms (each terminated by `;`):
///
/// ```text
/// let name = expr;        let mut name = expr;
/// print expr;             // println!("{}", expr)
/// expr;                   // evaluated, result discarded
/// ```
///
/// The block imports [`crate::prelude`] and expands *in place*, so bindings
/// stay visible to the surrounding code.
///
/// ```
/// use tpt_script::prelude::*;
/// let t = table_of(vec![f64s("v", vec![1.0, 5.0])]);
/// script! {
///     let big = t.filter("v", ">", 2.0);
///     print big.len();
/// }
/// assert_eq!(big.len(), 1);
/// ```
#[macro_export]
macro_rules! script {
    ($($body:tt)*) => {
        #[allow(unused_imports)]
        use $crate::prelude::*;
        $crate::script_stmt!($($body)*);
    };
}

#[doc(hidden)]
#[macro_export]
macro_rules! script_stmt {
    () => {};
    (let mut $n:ident = $e:expr; $($rest:tt)*) => {
        let mut $n = $e;
        $crate::script_stmt!($($rest)*);
    };
    (let $n:ident = $e:expr; $($rest:tt)*) => {
        let $n = $e;
        $crate::script_stmt!($($rest)*);
    };
    (print $e:expr; $($rest:tt)*) => {
        println!("{}", $e);
        $crate::script_stmt!($($rest)*);
    };
    ($e:expr; $($rest:tt)*) => {
        let _ = $e;
        $crate::script_stmt!($($rest)*);
    };
}

/// Generate the `main` of a `.tpt`-style file: runs a [`script!`] body under
/// [`run`], prints a traceback to stderr and exits `1` if it raises.
///
/// ```
/// mod my_script {
///     tpt_script::script_main! {
///         let xs = tpt_script::table_of(vec![tpt_script::f64s("v", vec![1.0, 2.0])]);
///         print xs.show();
///     }
/// }
/// my_script::main();
/// ```
#[macro_export]
macro_rules! script_main {
    ($($body:tt)*) => {
        /// Entry point generated by `tpt_script::script_main!`.
        pub fn main() {
            let outcome = $crate::run(|| {
                $crate::script! { $($body)* }
                Ok(())
            });
            if let Err(e) = outcome {
                eprintln!("{}", e.traceback());
                ::std::process::exit(1);
            }
        }
    };
}
