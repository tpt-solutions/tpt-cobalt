//! # tpt-script — the Pythonic scripting layer of the TPT stack
//!
//! A `.tpt` file is ordinary Rust with a script-shaped ergonomics layer:
//!
//! ```
//! use tpt_script::prelude::*;
//!
//! let t = table_of(vec![
//!     f64s("x", vec![-1.0, 2.0, 3.0]),
//!     strs("grp", &["a", "b", "a"]),
//! ]);
//!
//! script! {
//!     let pos = t.filter("x", ">", 0.0);
//!     let by_grp = pos.groupby(&["grp"]).agg(&[("x", "mean"), ("*", "count")]);
//!     print by_grp.show();
//! }
//! assert_eq!(pos.len(), 2);
//! assert_eq!(by_grp.len(), 2);
//! ```
//!
//! ## What is real here
//!
//! * [`prelude`] — one glob import for the whole stack with Pythonic names
//!   (`read`, `write`, `omni`, `stat`, `viz`, `sym`, ...).
//! * [`table::TableExt`] — real chaining on [`tpt_omni::Table`]: `.filter()`,
//!   `.groupby().agg()`, `.plot()` (a genuine [`tpt_viz::Plot`]), `.ols()`.
//! * [`script!`] — a `macro_rules!` block of Pythonic statements that expands
//!   to those calls, and [`script_main!`] which wraps a body in a `main` that
//!   prints a traceback and exits non-zero on failure.
//! * [`run`] / [`run_script`] — panic ("exception") capture with a
//!   Python-style traceback.
//!
//! ## Implicit error handling
//!
//! In script mode failures *raise* instead of returning `Result`: chaining
//! methods panic with a [`ScriptError`], and [`run`] converts that panic into
//! `Err(ScriptError)` with the panic location. So a script never writes `?`,
//! while library code can use the `try_*` twins (`try_filter`, `try_agg`,
//! `try_col_f64`, ...) and `?` with [`Res`].
//!
//! ## Scoped down (honest limits)
//!
//! * [`run_script`] does **not** compile Rust. The real `tpt script` binary
//!   generates `fn main` and calls `rustc`; here `run_script` executes a tiny
//!   documented statement language (`let` / `print` / `assert` / `panic` over
//!   f64 arithmetic) inside `catch_unwind`. See [`runner`].
//! * `.groupby()` keys are compared by their rendered string form; groups are
//!   emitted in lexicographic key order. Aggregations are `mean`, `sum`,
//!   `count`, `min`, `max`, `std`.
//! * `.plot()` produces a scatter of the first two numeric columns only.

